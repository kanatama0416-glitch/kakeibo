CREATE OR REPLACE FUNCTION private.kakeibo_capture_audit()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_before jsonb;
  v_after jsonb;
  v_actor_user_id uuid;
  v_actor_email text;
  v_record_id text;
  v_changed_fields text[] := array[]::text[];
begin
  v_actor_user_id := auth.uid();
  v_actor_email := nullif(auth.jwt() ->> 'email', '');

  if tg_op = 'INSERT' then
    v_after := to_jsonb(new);
    v_record_id := v_after ->> 'id';
    select coalesce(array_agg(key order by key), array[]::text[])
      into v_changed_fields
    from jsonb_object_keys(coalesce(v_after, '{}'::jsonb)) as x(key);
  elsif tg_op = 'UPDATE' then
    v_before := to_jsonb(old);
    v_after := to_jsonb(new);
    v_record_id := coalesce(v_after ->> 'id', v_before ->> 'id');

    select coalesce(array_agg(key order by key), array[]::text[])
      into v_changed_fields
    from jsonb_object_keys(coalesce(v_before, '{}'::jsonb) || coalesce(v_after, '{}'::jsonb)) as x(key)
    where (v_before -> key) is distinct from (v_after -> key);

    if coalesce(array_length(v_changed_fields, 1), 0) = 0 then
      return new;
    end if;
  elsif tg_op = 'DELETE' then
    v_before := to_jsonb(old);
    v_record_id := v_before ->> 'id';
    select coalesce(array_agg(key order by key), array[]::text[])
      into v_changed_fields
    from jsonb_object_keys(coalesce(v_before, '{}'::jsonb)) as x(key);
  else
    raise exception 'Unsupported audit operation: %', tg_op;
  end if;

  insert into public.audit_logs (
    actor_user_id,
    actor_email,
    action,
    table_name,
    record_id,
    changed_fields,
    before_data,
    after_data
  )
  values (
    v_actor_user_id,
    v_actor_email,
    tg_op,
    tg_table_name,
    v_record_id,
    v_changed_fields,
    v_before,
    v_after
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$function$
;

CREATE OR REPLACE FUNCTION private.kakeibo_effective_carry_out(p_month date)
 RETURNS integer
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_month date := date '2026-10-01';
  v_carry_in integer := 0;
  v_settlement integer;
  v_raw integer;
  v_out integer := 0;
begin
  if p_month < date '2026-10-01' then
    return 0;
  end if;

  while v_month <= p_month loop
    v_settlement := private.kakeibo_living_current(v_month) + v_carry_in;
    select c.amount into v_raw
      from public.monthly_carryovers c
     where c.category = 'living' and c.from_month = v_month;

    if v_raw is null or v_raw = 0 or v_settlement = 0
       or sign(v_raw) <> sign(v_settlement) then
      v_out := 0;
    else
      v_out := sign(v_settlement)::integer * least(abs(v_raw), abs(v_settlement));
    end if;

    v_carry_in := v_out;
    v_raw := null;
    v_month := (v_month + interval '1 month')::date;
  end loop;

  return v_out;
end;
$function$
;

