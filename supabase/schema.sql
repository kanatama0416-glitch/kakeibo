CREATE OR REPLACE FUNCTION public.kakeibo_undo_settlement_paid(p_settlement_month date)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_plan_id bigint;
  v_repayment_amount integer := 0;
begin
  select repayment_plan_id, amount
    into v_plan_id, v_repayment_amount
  from public.repayments
  where repayment_month = date_trunc('month', p_settlement_month)::date
    and is_demo = false
  limit 1
  for update;

  if v_plan_id is not null and coalesce(v_repayment_amount, 0) > 0 then
    delete from public.repayments
    where repayment_plan_id = v_plan_id
      and repayment_month = date_trunc('month', p_settlement_month)::date
      and is_demo = false;

    update public.repayment_plans
    set remaining_amount = least(original_amount, remaining_amount + v_repayment_amount)
    where id = v_plan_id
      and is_demo = false;
  end if;

  delete from public.monthly_settlements
  where settlement_month = date_trunc('month', p_settlement_month)::date;
end;
$function$
;

