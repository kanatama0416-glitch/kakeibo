CREATE OR REPLACE FUNCTION private.kakeibo_living_current(p_month date)
 RETURNS integer
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  with share as (
    select coalesce((select me_share_percent from public.app_settings where id = 1), 50) as pct
  ), tx as (
    select
      coalesce(sum(t.amount), 0)::numeric as total,
      coalesce(sum(t.amount) filter (where t.payer = 'me'), 0)::numeric as paid_by_me
    from public.transactions t
    where t.is_demo = false
      and t.scope = 'shared'
      and t.status in ('confirmed','refunded')
      and date_trunc('month', t.transaction_date)::date = p_month
  )
  select (tx.paid_by_me - floor(tx.total * share.pct / 100.0 + 0.5))::integer
  from tx, share;
$function$
;

CREATE OR REPLACE FUNCTION private.kakeibo_month_is_settled(p_date date)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select exists (
    select 1
    from public.monthly_settlements s
    where s.settlement_month = date_trunc('month', p_date)::date
  );
$function$
;

CREATE OR REPLACE FUNCTION private.kakeibo_recalculate_repayment_plan()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_total integer := 0;
  v_paid_by_me integer := 0;
  v_share integer := 50;
  v_my_share integer := 0;
  v_net integer := 0;
  v_original integer := 0;
  v_lender text;
  v_borrower text;
  v_plan public.repayment_plans%rowtype;
  v_repaid integer := 0;
begin
  select
    coalesce(sum(amount), 0)::integer,
    coalesce(sum(amount) filter (where payer = 'me'), 0)::integer
  into v_total, v_paid_by_me
  from public.initial_expenses;

  select coalesce(me_share_percent, 50)
  into v_share
  from public.app_settings
  where id = 1;

  v_share := coalesce(v_share, 50);
  v_my_share := round(v_total * v_share / 100.0);
  v_net := v_paid_by_me - v_my_share;
  v_original := abs(v_net);
  v_lender := case when v_net >= 0 then 'me' else 'partner' end;
  v_borrower := case when v_net >= 0 then 'partner' else 'me' end;

  select *
  into v_plan
  from public.repayment_plans
  where is_demo = false
  order by id
  limit 1
  for update;

  if not found then
    insert into public.repayment_plans (
      title, original_amount, remaining_amount, monthly_amount,
      lender, borrower, is_demo
    )
    values (
      '立替金', v_original, v_original, 0,
      v_lender, v_borrower, false
    );
    return;
  end if;

  select coalesce(sum(amount), 0)::integer
  into v_repaid
  from public.repayments
  where repayment_plan_id = v_plan.id
    and is_demo = false;

  if v_repaid > 0
     and (v_plan.lender is distinct from v_lender
          or v_plan.borrower is distinct from v_borrower) then
    raise exception 'REPAYMENT_DIRECTION_LOCKED';
  end if;

  if v_original < v_repaid then
    raise exception 'REPAYMENT_PRINCIPAL_BELOW_PAID';
  end if;

  update public.repayment_plans
  set original_amount = v_original,
      remaining_amount = greatest(0, v_original - v_repaid),
      lender = v_lender,
      borrower = v_borrower
  where id = v_plan.id
    and is_demo = false;
end;
$function$
;

CREATE OR REPLACE FUNCTION private.kakeibo_settlement_breakdown(p_month date)
 RETURNS TABLE(plan_id bigint, repayment_amount integer, final_amount integer)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_month date := date_trunc('month', p_month)::date;
  v_carry_in integer := 0;
  v_living_pay_now integer;
  v_plan public.repayment_plans%rowtype;
  v_recorded integer;
  v_setting integer;
  v_monthly integer;
  v_original integer;
  v_repaid_before integer;
  v_repayment integer := 0;
  v_has_plan boolean := false;
begin
  if not private.kakeibo_is_allowed() then
    raise exception 'KAKEIBO_NOT_ALLOWED';
  end if;

  if v_month > date '2026-10-01' then
    v_carry_in := private.kakeibo_effective_carry_out((v_month - interval '1 month')::date);
  end if;

  v_living_pay_now := private.kakeibo_living_current(v_month)
    + v_carry_in
    - private.kakeibo_effective_carry_out(v_month);

  select * into v_plan
    from public.repayment_plans
   where is_demo = false
   order by id
   limit 1;
  v_has_plan := found;

  if v_has_plan and v_month >= date '2026-10-01' then
    select r.amount into v_recorded
      from public.repayments r
     where r.repayment_plan_id = v_plan.id
       and r.repayment_month = v_month
       and r.is_demo = false
     limit 1;

    if v_recorded is not null then
      v_repayment := v_recorded;
    else
      select m.amount into v_setting
        from public.monthly_repayment_amounts m
       where m.repayment_plan_id = v_plan.id
         and m.repayment_month = v_month;

      v_monthly := greatest(0, coalesce(v_setting, v_plan.monthly_amount, 0));
      v_original := greatest(0, coalesce(v_plan.original_amount, 0));

      if v_monthly > 0 and v_original > 0 then
        select coalesce(sum(r.amount), 0)::integer into v_repaid_before
          from public.repayments r
         where r.repayment_plan_id = v_plan.id
           and r.is_demo = false
           and r.repayment_month < v_month;
        v_repayment := least(v_monthly, greatest(0, v_original - v_repaid_before));
      end if;
    end if;
  end if;

  plan_id := case when v_has_plan then v_plan.id else null end;
  repayment_amount := v_repayment;
  final_amount := v_living_pay_now
    + case when v_plan.lender = 'me' then v_repayment else -v_repayment end;
  return next;
end;
$function$
;

