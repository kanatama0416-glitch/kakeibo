-- 毎月の定額（家賃など）。
-- recurring_expenses に定額を登録し、public.kakeibo_apply_recurring_expenses() が
-- 開始月〜今月（日本時間）の各月に1件ずつ明細（transactions, source = 'manual'）を作る。
-- 規則は画面側の lib/recurring.js と同じ：
--   - 作り終えた月（last_generated_month）より後の月だけ作る。明細を削除しても同じ月は作り直さない。
--   - 日付は指定日。その月に指定日がなければ月末。
--   - 同じ定額・同じ月の明細は1件だけ（一意制約。2台の端末で同時に開いても重複しない）。
--   - 精算月は既存のトリガー（kakeibo_guard_transaction_settlement）が決める。

create table if not exists public.recurring_expenses (
  id bigint generated by default as identity primary key,
  name text not null,
  amount integer not null,
  category_id bigint references public.categories(id) on delete set null,
  scope text not null default 'shared',
  payer text not null default 'me',
  me_share_amount integer,
  day_of_month smallint not null,
  start_month date not null,
  last_generated_month date,
  is_active boolean not null default true,
  memo text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint recurring_expenses_name_check check (char_length(btrim(name)) between 1 and 100),
  constraint recurring_expenses_amount_check check (amount <> 0 and abs(amount) <= 100000000),
  constraint recurring_expenses_scope_check check (scope = any (array['shared'::text, 'mine'::text, 'partner'::text, 'advance'::text])),
  constraint recurring_expenses_payer_check check (payer = any (array['me'::text, 'partner'::text])),
  constraint recurring_expenses_me_share_amount_check check (
    me_share_amount is null
    or (scope = 'shared' and me_share_amount >= least(0, amount) and me_share_amount <= greatest(0, amount))
  ),
  constraint recurring_expenses_day_check check (day_of_month between 1 and 31),
  constraint recurring_expenses_start_month_check check (
    start_month = date_trunc('month', start_month)::date and start_month >= date '2026-10-01'
  ),
  constraint recurring_expenses_last_generated_month_check check (
    last_generated_month is null or last_generated_month = date_trunc('month', last_generated_month)::date
  )
);

alter table public.transactions
  add column if not exists recurring_expense_id bigint references public.recurring_expenses(id) on delete set null,
  add column if not exists recurring_month date;

alter table public.transactions
  drop constraint if exists transactions_recurring_month_key;
alter table public.transactions
  add constraint transactions_recurring_month_key unique (recurring_expense_id, recurring_month);

comment on column public.transactions.recurring_expense_id is '毎月の定額から自動で作った明細のとき、その定額。';
comment on column public.transactions.recurring_month is '毎月の定額から作った明細の対象月（月初）。同じ定額・同じ月は1件だけ。';

-- 権限：許可ユーザーだけ。
alter table public.recurring_expenses enable row level security;
revoke all on table public.recurring_expenses from public, anon, authenticated;
grant select, insert, update, delete on table public.recurring_expenses to authenticated;
grant usage, select on sequence public.recurring_expenses_id_seq to authenticated;

drop policy if exists "authorized user recurring expenses" on public.recurring_expenses;
create policy "authorized user recurring expenses"
  on public.recurring_expenses for all to authenticated
  using ((select private.kakeibo_is_allowed()))
  with check ((select private.kakeibo_is_allowed()));

-- 変更履歴（既存テーブルと同じ監査トリガー）。
drop trigger if exists kakeibo_audit_row_changes on public.recurring_expenses;
create trigger kakeibo_audit_row_changes
after insert or update or delete on public.recurring_expenses
for each row execute function private.kakeibo_capture_audit();

-- updated_at の更新と、作り終えた月の巻き戻し防止（画面から last_generated_month を古くさせない）。
create or replace function private.kakeibo_recurring_expense_before_update()
 returns trigger
 language plpgsql
 set search_path to ''
as $function$
begin
  new.updated_at := now();
  if old.last_generated_month is not null
     and (new.last_generated_month is null or new.last_generated_month < old.last_generated_month) then
    new.last_generated_month := old.last_generated_month;
  end if;
  return new;
end;
$function$;

drop trigger if exists kakeibo_recurring_expense_before_update on public.recurring_expenses;
create trigger kakeibo_recurring_expense_before_update
before update on public.recurring_expenses
for each row execute function private.kakeibo_recurring_expense_before_update();

-- 定額から今月までの明細を作る。作った件数を返す。
create or replace function public.kakeibo_apply_recurring_expenses()
 returns integer
 language plpgsql
 security definer
 set search_path to ''
as $function$
declare
  v_current date := date_trunc('month', (now() at time zone 'Asia/Tokyo'))::date;
  v_template public.recurring_expenses%rowtype;
  v_month date;
  v_day integer;
  v_inserted integer := 0;
  v_rows integer;
begin
  if not private.kakeibo_is_allowed() then
    raise exception 'NOT_ALLOWED';
  end if;

  for v_template in
    select * from public.recurring_expenses r
    where r.is_active = true
      and r.start_month <= v_current
      and (r.last_generated_month is null or r.last_generated_month < v_current)
    order by r.id
    for update
  loop
    v_month := greatest(
      v_template.start_month,
      date '2026-10-01',
      coalesce((v_template.last_generated_month + interval '1 month')::date, v_template.start_month)
    );

    while v_month <= v_current loop
      v_day := least(
        v_template.day_of_month,
        extract(day from (v_month + interval '1 month' - interval '1 day'))::integer
      );

      insert into public.transactions (
        transaction_date, merchant_name, amount, category_id, scope, payer, me_share_amount,
        status, source, memo, is_demo, recurring_expense_id, recurring_month
      ) values (
        v_month + (v_day - 1),
        v_template.name,
        v_template.amount,
        v_template.category_id,
        v_template.scope,
        v_template.payer,
        case when v_template.scope = 'shared' then v_template.me_share_amount else null end,
        case when v_template.amount < 0 then 'refunded' else 'confirmed' end,
        'manual',
        v_template.memo,
        false,
        v_template.id,
        v_month
      )
      on conflict (recurring_expense_id, recurring_month) do nothing;

      get diagnostics v_rows = row_count;
      v_inserted := v_inserted + v_rows;
      v_month := (v_month + interval '1 month')::date;
    end loop;

    update public.recurring_expenses
      set last_generated_month = v_current
      where id = v_template.id;
  end loop;

  return v_inserted;
end;
$function$;

revoke all on function public.kakeibo_apply_recurring_expenses() from public, anon;
grant execute on function public.kakeibo_apply_recurring_expenses() to authenticated;
