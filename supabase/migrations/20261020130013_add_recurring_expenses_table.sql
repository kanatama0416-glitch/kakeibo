-- 毎月の固定費（家賃など）。登録した内容から、開始月〜今月の各月に支出を1件ずつ自動で入れる。
-- 本番へは削除系の命令（drop）を使わず3つに分けて適用した（新しい表なので drop ... if exists は不要）。
-- 20261020130013_add_recurring_expenses_table / 20261020130024_add_recurring_expenses_access / 20261020130041_add_recurring_expenses_generate
-- 月の数え方は lib/recurring.js（monthsToGenerate / occurrenceDate）と同じ。

create table if not exists public.recurring_expenses (
  id bigint generated by default as identity primary key,
  name text not null,
  amount integer not null,
  day_of_month smallint not null,
  category_id bigint references public.categories(id) on delete set null,
  scope text not null,
  payer text not null,
  me_share_amount integer,
  memo text,
  start_month date not null,
  last_generated_month date,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint recurring_expenses_name_check check (char_length(btrim(name)) between 1 and 100),
  constraint recurring_expenses_amount_check check (amount > 0 and amount <= 10000000),
  constraint recurring_expenses_day_check check (day_of_month between 1 and 31),
  -- 個人の分（mine / partner）は精算・集計に入らないので固定費にしない。
  constraint recurring_expenses_scope_check check (scope in ('shared', 'advance')),
  constraint recurring_expenses_payer_check check (payer in ('me', 'partner')),
  constraint recurring_expenses_me_share_amount_check check (
    me_share_amount is null
    or (scope = 'shared' and me_share_amount between 0 and amount)
  ),
  constraint recurring_expenses_memo_check check (memo is null or char_length(memo) <= 200),
  constraint recurring_expenses_start_month_check check (
    start_month = date_trunc('month', start_month)::date
    and start_month >= date '2026-01-01'
  ),
  constraint recurring_expenses_last_generated_month_check check (
    last_generated_month is null
    or (last_generated_month = date_trunc('month', last_generated_month)::date
        and last_generated_month >= start_month)
  )
);

comment on table public.recurring_expenses is '毎月の固定費。kakeibo_generate_recurring_expenses() が各月の支出を作る。';
comment on column public.recurring_expenses.last_generated_month is '支出を入れ終わった最後の月。null はまだ1件も入れていない。';

alter table public.recurring_expenses enable row level security;
